/********************************************************************************************************
* @ name   : static void IO_Init(void)
* @ msg    : GPIO初始化
* @ param   (*)
* @ return  (*)
 ********************************************************************************************************/
static void IO_Init(void)
{
	//TK对应的IO设置为强推挽输出
	P0 = _BIN(00000000);
	P1 = _BIN(00000000);	
	P2 = _BIN(00000000);
	P5 = _BIN(00000000); 	
	
	P0CON = _BIN(11111111);			
	P0PH  = _BIN(11111111);	
	
	P1CON = _BIN(11111111);  
	P1PH  = _BIN(11111111);	 
	
	P2CON = _BIN(11111111);
	P2PH  = _BIN(11111111);
	
	P5CON = _BIN(11111111);
	P5PH  = _BIN(11111111);
	
	P0 = _BIN(00000000);
	P1 = _BIN(00000000);
	P2 = _BIN(00000000);
	P5 = _BIN(00000000);	
}

/********************************************************************************************************
* @ name   : void Timer_Init(void)
* @ msg    : 定时器初始化
* @ param   (*)
* @ return  (*)
 ********************************************************************************************************/
static void Timer0_Init(void)
{
	TMCON = (TMCON & 0xfe)|(0 << 0);	//bit0: 0为FOSC/12,1为FOSO
	TMOD = TMOD & 0xf0;		  			//设置定时0，工作方式0
	TMOD = TMOD | 0x02;
	TH0 = (256 - 125);       				//1000*1=1000us	,1MS
	TL0 = (256 - 125);
	TF0 = 0;						    //清中断标志
	TR0 = 0;							//关定时器0
   	ET0 = 1;							//使能定时器0中断
	IPT0 = 1;
	TR0 = 1;
}





void WDT_Init(void)
{
	WDTCON  = 0x10;				    //1--1 -- 00    开WDT,WDT清0,WDT 524.288ms溢出;烧录时，可Code Option选择ENWDT

}


